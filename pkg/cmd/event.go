var eventsRetrieve = cli.Command{
	Name:    "retrieve",
	Usage:   "Get event",
	Suggest: true,
	Flags: []cli.Flag{
		&requestflag.String{
			Name:      "id",
			Required:  true,
			PathParam: "id",
		},
	},
	Action:          handleEventsRetrieve,
	HideHelpCommand: true,
}

